// Builds src/data/lifemap.js, the base map for the Life of Christ tab.
// Inputs (download separately; not stored in this repository):
//   1. @geo-maps/earth-coastlines-100m and @geo-maps/earth-lakes-100m (npm, OpenStreetMap data, ODbL)
//   2. OpenBible.info Bible-Geocoding-Data (GitHub, CC BY 4.0): geometry/ae686c9.geojson, the Jordan River
// Usage: node tools/make_life_map.js <geo-maps node_modules/@geo-maps dir> <Bible-Geocoding-Data dir>
const fs=require('fs'),path=require('path');
const [gm,ob]=process.argv.slice(2);
if(!gm||!ob){console.error('usage: node tools/make_life_map.js <@geo-maps dir> <Bible-Geocoding-Data dir>');process.exit(1)}
const V={w:33.95,e:36.35,s:30.95,n:33.7};   // data window, degrees
const K=440,KX=K*Math.cos(32.3*Math.PI/180);
const P=([lon,lat])=>[+((lon-V.w)*KX).toFixed(1),+((V.n-lat)*K).toFixed(1)];
const W=+((V.e-V.w)*KX).toFixed(1),H=+((V.n-V.s)*K).toFixed(1);
const inb=(c,m=0.25)=>c[0]>=V.w-m&&c[0]<=V.e+m&&c[1]>=V.s-m&&c[1]<=V.n+m;
const geoms=g=>g.type==='GeometryCollection'?g.geometries:g.type==='FeatureCollection'?g.features.map(f=>f.geometry):[g];
const rings=g=>({Polygon:()=>g.coordinates,MultiPolygon:()=>g.coordinates.flat(),LineString:()=>[g.coordinates],MultiLineString:()=>g.coordinates}[g.type]||(()=>[]))();
const runs=(file)=>{const out=[];for(const g of geoms(JSON.parse(fs.readFileSync(file))))for(const l of rings(g)){let r=[];for(const c of l){if(inb(c))r.push(c);else{if(r.length>1)out.push(r);r=[]}}if(r.length>1)out.push(r)}return out};
// simplify (Douglas-Peucker in map units)
function dp(pts,eps){if(pts.length<3)return pts;let i0=0,dm=0;const [a,b]=[pts[0],pts[pts.length-1]];
  for(let i=1;i<pts.length-1;i++){const p=pts[i];const dx=b[0]-a[0],dy=b[1]-a[1];const L=Math.hypot(dx,dy)||1;const d=Math.abs(dy*p[0]-dx*p[1]+b[0]*a[1]-b[1]*a[0])/L;if(d>dm){dm=d;i0=i}}
  return dm>eps?[...dp(pts.slice(0,i0+1),eps).slice(0,-1),...dp(pts.slice(i0),eps)]:[a,b]}
const dpRing=(pts,eps)=>{const h=Math.floor(pts.length/2);return [...dp(pts.slice(0,h+1),eps).slice(0,-1),...dp(pts.slice(h),eps)]};
const d=(pts,close)=>'M'+pts.map(p=>p.join(',')).join('L')+(close?'Z':'');
// coastline: the longest run, south to north; sea is to its west
const coast=runs(path.join(gm,'earth-coastlines-100m/map.geo.json')).sort((a,b)=>b.length-a.length)[0];
let cp=dp(coast.map(P),0.6);if(cp[0][1]<cp[cp.length-1][1])cp.reverse();
if(!((cp[0][1]>H||cp[0][0]<0)&&cp[cp.length-1][1]<0))throw new Error('coastline does not cross the whole map: '+JSON.stringify([cp[0],cp[cp.length-1]]));
const sea=d([...cp,[-400,cp[cp.length-1][1]],[-400,cp[0][1]]],true);
// lakes: the Sea of Galilee and the Dead Sea (both Dead Sea basins); skip small reservoirs
const area=r=>{let a=0;for(let i=0;i<r.length-1;i++)a+=r[i][0]*r[i+1][1]-r[i+1][0]*r[i][1];return Math.abs(a/2)};
const lakes=runs(path.join(gm,'earth-lakes-100m/map.geo.json')).filter(r=>area(r)>0.012&&r.every(c=>c[0]>35.3&&c[0]<35.8&&c[1]>30.9&&c[1]<33)).map(r=>d(dpRing(r.map(P),0.5),true));
if(lakes.length<2)throw new Error('expected the Sea of Galilee and the Dead Sea');
// Jordan: OpenBible's simplified OpenStreetMap course
const jg=JSON.parse(fs.readFileSync(path.join(ob,'geometry/ae686c9.geojson')));
const lines=[];(function walk(o){if(Array.isArray(o))o.forEach(walk);else if(o&&typeof o==='object'){if(o.type==='LineString')lines.push(o.coordinates);Object.values(o).forEach(walk)}})(jg);
const jl=lines.sort((a,b)=>a.length-b.length).find(l=>l.length>20&&l.length<400)||lines[0];
const jordan=d(dp(jl.map(P),0.4));
const out=`// Generated by tools/make_life_map.js. Do not edit by hand.
// Coastline and lakes: OpenStreetMap contributors (ODbL), via geo-maps. Jordan River: OpenStreetMap via OpenBible.info (CC BY 4.0).
// Modern shorelines; map units: x=(lon-${V.w})*${KX.toFixed(3)}, y=(${V.n}-lat)*${K}.
const LIFEMAP=${JSON.stringify({w:W,h:H,lon0:V.w,lat0:V.n,k:K,kx:+KX.toFixed(3),sea,lakes,jordan})};
`;
fs.writeFileSync(path.join(__dirname,'../src/data/lifemap.js'),out);
console.log('wrote src/data/lifemap.js',out.length,'bytes; lakes',lakes.length);
